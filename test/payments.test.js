async function pending(p, user = 'tg:2', suffix = '0001', receipt = null) { const r = (await p.createDeposit(user, { method: 'cbe', amount: 10000 }, 'create-' + suffix)); (await p.submitProof(user, r.id, { reference: receipt ? '' : 'FT' + suffix + 'ABC', senderName: 'Alice Bank Name', receipt }, 'proof-' + suffix)); return r; }
function approval(ref = 'FT0001ABC') { return { action: 'approve', verifiedReference: ref, verifiedAmount: 10000, verifiedRecipient: receiver, verifiedSender: 'Alice Bank Name', bankConfirmed: true }; }
test('deposit needs independent review, credits once, and never mixes with test credits', async (t) => {
    const { store, payments: p } = (await fixture(t));
    (await store.deposit('tg:2', 500000, 'test-credits'));
    const r = (await pending(p));
    assert.equal((await p.balance('tg:2')).available, 0);
    (await assert.rejects(async () => (await p.review('tg:2', r.id, approval(), 'unauthorized')), /access required/));
    (await assert.rejects(async () => (await p.review('tg:1', r.id, { ...approval(), bankConfirmed: false }, 'unconfirmed')), /Confirm receipt/));
    (await assert.rejects(async () => (await p.review('tg:1', r.id, { ...approval(), verifiedAmount: 9999 }, 'wrong-amount')), /exact amount/));
    (await assert.rejects(async () => (await p.review('tg:1', r.id, { ...approval(), verifiedRecipient: '1000000000000' }, 'wrong-receiver')), /receiving account/));
    const approved = (await p.review('tg:1', r.id, approval(), 'approve-0001'));
    assert.equal(approved.status, 'approved');
    assert.equal((await p.balance('tg:2')).available, 10000);
    assert.deepEqual((await p.review('tg:1', r.id, approval(), 'approve-0001')), approved);
    (await assert.rejects(async () => (await p.review('tg:1', r.id, approval(), 'approve-again')), /current request status/));
    assert.equal((await store.balance('tg:2')).available, 500000);
    assert.equal((await p.balance('tg:2')).available, 10000);
    assert.equal((await store.db.prepare('SELECT SUM(amount) AS n FROM entries').get()).n, 0);
});
test('screenshot-only proof stays pending, receipts are private and verified references cannot be reused', async (t) => {
    const { payments: p } = (await fixture(t));
    const a = (await pending(p, 'tg:2', '0001', image));
    assert.equal((await p.row(a.id)).status, 'pending');
    assert.equal((await p.receiptFor('tg:2', a.id)).type, 'image/png');
    (await assert.rejects(async () => (await p.receiptFor('tg:4', a.id)), /not found/));
    (await p.review('tg:1', a.id, approval(), 'approve-first'));
    const b = (await pending(p, 'tg:4', '0002', image));
    (await assert.rejects(async () => (await p.review('tg:1', b.id, approval(), 'duplicate-bank')), /already used/));
    assert.equal((await p.balance('tg:4')).available, 0);
    assert.equal((await p.row(b.id)).status, 'pending');
    const bad = (await p.createDeposit('tg:2', { method: 'cbe', amount: 100 }, 'invalid-file'));
    (await assert.rejects(async () => (await p.submitProof('tg:2', bad.id, { senderName: 'Alice', receipt: { type: 'image/svg+xml', base64: 'PHN2Zz4=' } }, 'invalid-proof')), /PNG or JPEG/));
    (await assert.rejects(async () => (await p.submitProof('tg:2', bad.id, { senderName: 'Alice' }, 'missing-proof')), /transaction ID or/));
});
test('daily account switching preserves old recipient snapshots and assigned-agent access', async (t) => {
    const { payments: p } = (await fixture(t));
    (await p.setAgent('tg:1', { telegramId: '3', enabled: true }, 'enable-agent'));
    (await assert.rejects(async () => (await p.settingsFor('tg:3')), /Owner access/));
    assert.ok((await p.settingsFor('tg:1')).users.some(u => u.id === 'tg:4'));
    const old = (await pending(p));
    (await p.addAccount('tg:1', { method: 'cbe', account: '1000000000000', holder: 'Agent Receiver', agentId: '3' }, 'switch-account'));
    const next = (await p.createDeposit('tg:4', { method: 'cbe', amount: 10000 }, 'new-deposit'));
    assert.equal(next.receiver_account, '1000000000000');
    assert.equal((await p.row(old.id)).receiver_account, receiver);
    (await assert.rejects(async () => (await p.review('tg:3', old.id, approval(), 'agent-not-assigned')), /assigned to another/));
    (await p.submitProof('tg:4', next.id, { reference: 'NEWREF123', senderName: 'Bob' }, 'next-proof'));
    assert.equal((await p.queue('tg:3')).length, 1);
    (await p.review('tg:3', next.id, { ...approval('NEWREF123'), verifiedRecipient: '1000000000000' }, 'agent-approval'));
    assert.equal((await p.balance('tg:4')).available, 10000);
    (await assert.rejects(async () => (await p.addAccount('tg:3', { method: 'cbe', account: receiver, holder: 'No' }, 'not-owner')), /Owner access/));
    (await p.setAgent('tg:1', { telegramId: '3', enabled: false }, 'disable-agent'));
    assert.equal((await p.role('tg:3')), null);
    (await assert.rejects(async () => (await p.queue('tg:3')), /access required/));
    assert.equal((await p.methods()).methods.find(m => m.id === 'cbe').available, false);
});
test('withdrawals reserve cash only, claims are exclusive, paid and failed transitions are balanced', async (t) => {
    const { store, payments: p } = (await fixture(t));
    (await store.deposit('tg:2', 500000, 'sandbox-funds'));
    (await assert.rejects(async () => (await p.createWithdrawal('tg:2', { method: 'telebirr', amount: 100, account: '0940646657', holder: 'Alice' }, 'test-cannot-withdraw')), /Insufficient balance/));
    const d = (await pending(p));
    (await p.review('tg:1', d.id, approval(), 'fund-wallet'));
    const w = (await p.createWithdrawal('tg:2', { method: 'telebirr', amount: 6000, account: '0940646657', holder: 'Alice' }, 'withdraw-request'));
    assert.equal((await p.balance('tg:2')).available, 4000);
    assert.equal((await p.balance('tg:2')).reserved, 6000);
    assert.equal((await p.createWithdrawal('tg:2', { method: 'telebirr', amount: 6000, account: '0940646657', holder: 'Alice' }, 'withdraw-request')).id, w.id);
    (await assert.rejects(async () => (await p.createWithdrawal('tg:2', { method: 'cbe', amount: 5000, account: receiver, holder: 'Alice' }, 'overdraft')), /Insufficient/));
    (await p.review('tg:1', w.id, { action: 'claim' }, 'claim-withdrawal'));
    (await p.setAgent('tg:1', { telegramId: '3', enabled: true }, 'second-reviewer'));
    (await assert.rejects(async () => (await p.review('tg:3', w.id, { action: 'claim' }, 'other-claim')), /current request/));
    (await assert.rejects(async () => (await p.cancel('tg:2', w.id, 'cancel-processing')), /no longer/));
    const paid = { action: 'paid', verifiedReference: 'PAYOUT123', verifiedAmount: 6000, verifiedRecipient: '0940646657', bankConfirmed: true };
    (await assert.rejects(async () => (await p.review('tg:3', w.id, paid, 'other-payout')), /assigned reviewer/));
    (await p.review('tg:1', w.id, paid, 'confirm-payout'));
    assert.equal((await p.balance('tg:2')).reserved, 0);
    assert.equal((await p.balance('tg:2')).available, 4000);
    (await assert.rejects(async () => (await p.review('tg:1', w.id, paid, 'payout-twice')), /current request/));
    const failed = (await p.createWithdrawal('tg:2', { method: 'cbe', amount: 1000, account: receiver, holder: 'Alice' }, 'withdraw-failure'));
    (await p.review('tg:3', failed.id, { action: 'claim' }, 'claim-failure'));
    (await assert.rejects(async () => (await p.setAgent('tg:1', { telegramId: '3', enabled: false }, 'disable-busy')), /Resolve/));
    (await assert.rejects(async () => (await p.review('tg:3', failed.id, { action: 'failed', reason: 'Unknown result', fundsNotSent: false }, 'uncertain-payout')), /no funds were sent/));
    assert.equal((await p.balance('tg:2')).reserved, 1000);
    (await p.review('tg:3', failed.id, { action: 'failed', reason: 'Transfer was declined', fundsNotSent: true }, 'failed-payout'));
    assert.equal((await p.balance('tg:2')).available, 4000);
    assert.equal((await p.balance('tg:2')).reserved, 0);
    assert.equal((await store.db.prepare('SELECT SUM(amount) AS n FROM entries').get()).n, 0);
});
test('cancellation and rejection release reserved funds once and disallow self review', async (t) => {
    const { payments: p } = (await fixture(t));
    const d = (await pending(p));
    (await p.review('tg:1', d.id, approval(), 'fund-wallet'));
    const make = async (key) => (await p.createWithdrawal('tg:2', { method: 'cbe', amount: 2000, account: receiver, holder: 'Alice' }, key));
    const a = (await make('cancel-me'));
    (await p.cancel('tg:2', a.id, 'cancel-first'));
    assert.equal((await p.balance('tg:2')).available, 10000);
    (await assert.rejects(async () => (await p.cancel('tg:2', a.id, 'cancel-again')), /no longer/));
    const b = (await make('reject-me'));
    (await p.review('tg:1', b.id, { action: 'reject', reason: 'Incorrect account details' }, 'reject-first'));
    assert.equal((await p.balance('tg:2')).available, 10000);
    const self = (await pending(p, 'tg:1', '9999'));
    (await assert.rejects(async () => (await p.review('tg:1', self.id, approval('FT9999ABC'), 'self-approval')), /own payment/));
});
test('HTTP payment routes enforce authentication, reviewer roles, receipt privacy and request size', async (t) => {
    const { store, config } = (await fixture(t));
    const server = (await createApp(config, store));
    await new Promise(r => server.listen(0, '127.0.0.1', r));
    t.after(() => new Promise(r => server.close(r)));
    const base = `http://127.0.0.1:${server.address().port}`;
    (await store.session('tg:2', 'alice-token'));
    (await store.session('tg:4', 'bob-token'));
    (await store.session('tg:1', 'owner-token'));
    const send = (path, data, token = 'alice-token', key = 'http-request') => fetch(base + path, { method: data === undefined ? 'GET' : 'POST', headers: { Authorization: `Bearer ${token}`, ...(data === undefined ? {} : { 'Content-Type': 'application/json', 'Idempotency-Key': key }) }, body: data === undefined ? undefined : JSON.stringify(data) });
    assert.equal((await fetch(base + '/api/payments')).status, 401);
    assert.equal((await send('/api/admin/payments')).status, 403);
    assert.deepEqual(await (await send('/api/chicken-road/activity')).json(), {bets: []});
    assert.deepEqual(await (await send('/api/aviator/activity')).json(), {bets: []});
    const d = await (await send('/api/payments/deposits', { method: 'cbe', amount: 10000 })).json();
    assert.equal(d.receiver_account, receiver);
    assert.equal((await send(`/api/payments/${d.id}/proof`, { senderName: 'Alice', receipt: image }, 'alice-token', 'http-proof')).status, 200);
    assert.equal((await send(`/api/payments/${d.id}/receipt`)).status, 200);
    assert.equal((await send(`/api/payments/${d.id}/receipt`, undefined, 'bob-token')).status, 404);
    assert.equal((await send(`/api/admin/payments/${d.id}/review`, approval(), 'alice-token', 'illegal-review')).status, 403);
    assert.equal((await send(`/api/admin/payments/${d.id}/review`, approval(), 'owner-token', 'valid-review')).status, 200);
    assert.equal((await (await send('/api/payments')).json()).wallet.available, 10000);
    assert.equal((await send('/api/payments/deposits', { method: 'cbe', amount: 100, extra: 'x'.repeat(17000) }, 'alice-token', 'large-request')).status, 413);
});
test('simple deposit decisions use stored details, support screenshots and remain duplicate-safe', async (t) => {
    const { payments: p } = (await fixture(t));
    const a = (await pending(p));
    const approved = (await p.review('tg:1', a.id, { action: 'approve' }, 'simple-approve'));
    assert.equal(approved.status, 'approved');
    assert.equal((await p.balance('tg:2')).available, 10000);
    assert.deepEqual((await p.review('tg:1', a.id, { action: 'approve' }, 'simple-approve')), approved);
    (await assert.rejects(async () => (await p.review('tg:1', a.id, { action: 'approve' }, 'second-approve')), /current request/));
    const screenshot = (await pending(p, 'tg:4', 'shot1', image));
    (await p.review('tg:1', screenshot.id, { action: 'approve' }, 'approve-shot'));
    assert.equal((await p.row(screenshot.id)).reference, null);
    assert.equal((await p.balance('tg:4')).available, 10000);
    const duplicate = (await pending(p, 'tg:2', 'shot2', image));
    (await assert.rejects(async () => (await p.review('tg:1', duplicate.id, { action: 'approve' }, 'approve-duplicate')), /receipt was already used/));
    const rejected = (await p.review('tg:1', duplicate.id, { action: 'reject' }, 'simple-reject'));
    assert.equal(rejected.status, 'rejected');
    assert.equal((await p.balance('tg:2')).available, 10000);
    const repeated = (await pending(p, 'tg:4', '0001'));
    (await assert.rejects(async () => (await p.review('tg:1', repeated.id, { action: 'approve' }, 'duplicate-ref')), /already used/));
    (await assert.rejects(async () => (await p.review('tg:4', repeated.id, { action: 'approve' }, 'unauthorized-simple')), /access required/));
    assert.equal((await p.auditFor('tg:1', screenshot.id)).at(-1).details.confirmation, 'Reviewer approved receipt of funds');
});
