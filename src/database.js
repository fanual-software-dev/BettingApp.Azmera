import { AsyncLocalStorage } from 'node:async_hooks';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
import pg from 'pg';
import { schemaStatements } from './schema.js';

const TRANSACTION_LOCK = 20261101;
function safeNumber(value) {
  const number = Number(value);
  if (!Number.isSafeInteger(number)) throw new Error('Database integer exceeds safe range');
  return number;
}
// SQL is application-owned. Values always remain bound parameters.
export function postgresSql(sql) {
  let index = 0, quote = null, output = '';
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (quote) {
      output += c;
      if (c === quote) { if (sql[i + 1] === quote) output += sql[++i]; else quote = null; }
    } else if (c === "'" || c === '"') { quote = c; output += c; }
    else output += c === '?' ? `$${++index}` : c;
  }
  if (/INSERT OR IGNORE/i.test(output)) output = output.replace(/INSERT OR IGNORE/i, 'INSERT') + ' ON CONFLICT DO NOTHING';
  return output;
}

export class Database {
  constructor(kind, connection) { this.kind = kind; this.connection = connection; this.context = new AsyncLocalStorage(); this.tail = Promise.resolve(); }
  async exclusive(fn) {
    const previous = this.tail;
    let release;
    this.tail = new Promise(resolve => { release = resolve; });
    await previous;
    try { return await fn(); } finally { release(); }
  }
  async query(sql, params = []) {
    const active = this.context.getStore();
    if (this.kind === 'postgres') {
      const result = await (active || this.connection).query(postgresSql(sql), params);
      return { rows: result.rows, changes: result.rowCount };
    }
    const execute = () => {
      const stmt = this.connection.prepare(sql.replace(/ORDER BY sequence DESC/g, 'ORDER BY rowid DESC'));
      if (/^\s*(SELECT|WITH|PRAGMA)/i.test(sql)) return { rows: stmt.all(...params), changes: 0 };
      return { rows: [], ...stmt.run(...params) };
    };
    return active ? execute() : this.exclusive(execute);
  }
  prepare(sql) {
    return {
      get: async (...params) => (await this.query(sql, params)).rows[0],
      all: async (...params) => (await this.query(sql, params)).rows,
      run: async (...params) => { const { changes } = await this.query(sql, params); return { changes }; },
    };
  }
  async exec(sql) {
    const active = this.context.getStore();
    if (this.kind === 'postgres') return (active || this.connection).query(sql);
    return active ? this.connection.exec(sql) : this.exclusive(() => this.connection.exec(sql));
  }
  async transaction(fn) {
    if (this.context.getStore()) return fn();
    if (this.kind === 'sqlite') return this.exclusive(async () => {
      this.connection.exec('BEGIN IMMEDIATE');
      try { const result = await this.context.run(this.connection, fn); this.connection.exec('COMMIT'); return result; }
      catch (error) { this.connection.exec('ROLLBACK'); throw error; }
    });
    const client = await this.connection.connect();
    try {
      await client.query('BEGIN');
      // Preserve the existing single-writer ledger semantics across backend instances.
      // Transaction-scoped lock works with both session and transaction poolers.
      await client.query('SELECT pg_advisory_xact_lock($1)', [TRANSACTION_LOCK]);
      const result = await this.context.run(client, fn);
      await client.query('COMMIT'); return result;
    } catch (error) { await client.query('ROLLBACK').catch(() => {}); throw error; }
    finally { client.release(); }
  }
  async initialize() {
    await this.transaction(async () => {
      if (this.kind === 'postgres') {
        await this.exec('CREATE SCHEMA IF NOT EXISTS azmera');
        await this.exec('REVOKE ALL ON SCHEMA azmera FROM PUBLIC');
      }
      for (let sql of schemaStatements) {
        if (this.kind === 'postgres') {
          sql = sql.replace(/\bINTEGER\b/g, 'BIGINT').replace(/\bBLOB\b/g, 'BYTEA');
          if (/CREATE TABLE IF NOT EXISTS (entries|payment_audit)\(/.test(sql)) sql = sql.replace('id BIGINT PRIMARY KEY', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
          sql = sql.replace('sequence BIGINT PRIMARY KEY', 'sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
        }
        await this.exec(sql);
      }
      if (this.kind === 'postgres') {
        // This schema is backend-only, never a Supabase browser Data API schema.
        await this.exec('REVOKE ALL ON ALL TABLES IN SCHEMA azmera FROM PUBLIC');
        await this.exec(`DO $$ BEGIN
          IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
            REVOKE ALL ON SCHEMA azmera FROM anon;
            REVOKE ALL ON ALL TABLES IN SCHEMA azmera FROM anon;
          END IF;
          IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
            REVOKE ALL ON SCHEMA azmera FROM authenticated;
            REVOKE ALL ON ALL TABLES IN SCHEMA azmera FROM authenticated;
          END IF;
        END $$`);
      }
    });
  }
  async close() { if (this.kind === 'postgres') await this.connection.end(); else await this.exclusive(() => this.connection.close()); }
}

export async function openDatabase(connection) {
  const options = typeof connection === 'string' ? { databasePath: connection } : connection;
  if (options.databaseDriver === 'postgres' && !options.databaseUrl) throw new Error('DATABASE_URL is required for PostgreSQL');
  if (options.databaseUrl) {
    let url;
    try { url = new URL(options.databaseUrl); } catch { throw new Error('DATABASE_URL must be a PostgreSQL connection URL'); }
    if (!['postgres:', 'postgresql:'].includes(url.protocol)) throw new Error('DATABASE_URL must use postgres or postgresql');
    const local = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
    if (options.databaseSsl === false && !local) throw new Error('TLS may only be disabled for a loopback PostgreSQL server');
    // Explicit TLS verification cannot be weakened by connection-string sslmode options.
    for (const key of ['sslmode','sslcert','sslkey','sslrootcert','uselibpqcompat','options']) url.searchParams.delete(key);
    const pool = new pg.Pool({
      connectionString: url.href,
      ssl: options.databaseSsl === false ? false : { rejectUnauthorized: true, ...(options.databaseCa ? { ca: options.databaseCa.replace(/\\n/g, '\n') } : {}) },
      max: options.databasePoolSize || 5,
      connectionTimeoutMillis: 10000, idleTimeoutMillis: 30000,
      options: '-c search_path=azmera -c statement_timeout=15000 -c idle_in_transaction_session_timeout=30000',
      types: { getTypeParser: (oid, format) => [20,1700].includes(oid) && format !== 'binary' ? safeNumber : pg.types.getTypeParser(oid, format) },
    });
    pool.on('error', () => console.error('PostgreSQL pool connection error'));
    return new Database('postgres', pool);
  }
  const { DatabaseSync } = await import('node:sqlite');
  const filename = options.databasePath || ':memory:';
  if (filename !== ':memory:') mkdirSync(path.dirname(filename), { recursive: true });
  const sqlite = new DatabaseSync(filename);
  sqlite.exec('PRAGMA foreign_keys=ON; PRAGMA journal_mode=WAL; PRAGMA busy_timeout=5000;');
  return new Database('sqlite', sqlite);
}
